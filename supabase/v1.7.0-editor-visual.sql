create or replace function public.set_editor_visual_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at=now(); return new; end;
$$;

drop trigger if exists catalogo_paginas_updated_at on public.catalogo_paginas;
create trigger catalogo_paginas_updated_at before update on public.catalogo_paginas
for each row execute function public.set_editor_visual_updated_at();

drop trigger if exists pagina_elementos_updated_at on public.pagina_elementos;
create trigger pagina_elementos_updated_at before update on public.pagina_elementos
for each row execute function public.set_editor_visual_updated_at();

